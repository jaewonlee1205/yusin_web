/**
 * 격자에 깔린 칸이 **몇 번째 열**에 놓이는지 센다.
 *
 * 쓰는 곳은 **선표 셋**이다 — 회사 개요(company/page.tsx) · 오시는 길
 * 연락처(location/page.tsx) · 제품 규격표(products/[slug]/page.tsx).
 * 셋 다 2026-10-19 에 **열 사이에 세로 hairline** 을 넣으면서 "둘째 열부터
 * 왼쪽 선을 긋는다" 가 필요해졌다.
 *
 * ⚠️⚠️ **CSS 로는 못 고른다.** 격자에서 "둘째 열에 놓인 칸" 을 집는 선택자가
 *    없고, `nth-child(2n)` 은 전폭 행(col-span-2)이 하나 끼는 순간 어긋난다.
 *    그래서 **데이터에서 센다.**
 *
 * ⚠️ 브라우저의 자동 배치 규칙을 흉내 낸 것이라, 전폭 행이 **줄 가운데**에
 *    끼면 빈칸이 생기고 그 뒤 열이 밀린다. 그 경우까지 맞춘다 —
 *    전폭 행을 만나면 (ㄱ) 쓰던 줄을 닫고 (ㄴ) 자기도 한 줄을 통째로 쓰므로
 *    다음 칸은 새 줄 첫 열에서 시작한다.
 *
 * ⚠️ 그래도 **눈으로 맞춰 보는 것을 대신하지 않는다.** 행을 더하거나 wide 를
 *    섞은 뒤에는 DOM 좌표로 재서 이 계산과 같은지 확인한다(그 검사를 돌린
 *    기록이 세 쪽의 주석에 있다).
 *
 * ⚠️ **짝 함수가 아래에 있다 — `gridRows`.** 2026-10-20 에 홀수 행 줄무늬를
 *    넣으면서 **행 번호**도 필요해졌다. 배치 규칙이 똑같으므로 **둘을 따로
 *    고치지 말 것** — 한쪽만 고치면 열과 행이 어긋난다.
 *
 * @param isWide i 번째 칸이 한 줄을 통째로 쓰는가
 * @returns 칸마다의 열 번호(0부터). 전폭 칸은 늘 0 이다.
 */
export function gridColumns(
  count: number,
  cols: number,
  isWide: (i: number) => boolean = () => false,
): number[] {
  const out: number[] = [];
  let col = 0;
  for (let i = 0; i < count; i++) {
    if (isWide(i)) {
      out.push(0);
      col = 0; // 전폭 칸이 줄을 닫는다 — 다음은 새 줄 첫 열이다
      continue;
    }
    out.push(col);
    col = (col + 1) % cols;
  }
  return out;
}

/**
 * 격자에 깔린 칸이 **몇 번째 행**에 놓이는지 센다. 위 `gridColumns` 의 짝이고
 * **배치 규칙이 똑같다** — 전폭 칸은 (ㄱ) 쓰던 줄을 닫고 (ㄴ) 자기도 한 줄을
 * 통째로 쓴다.
 *
 * 2026-10-20 에 **홀수 행 줄무늬** 때문에 생겼다. 유신이 레퍼런스
 * (honeyppl.kr/ko/sub1_2.html)를 보고 *"홀수 행들은 색깔이 달라서"* 라고 했다.
 *
 * ⚠️⚠️ **`nth-child` 로는 못 한다.** 위 주석과 같은 까닭에 더해 **하나가 더**
 *    있다 — 2열 격자에서 `nth-child(odd)` 는 **한 행의 왼쪽 칸만** 집으므로
 *    가로 줄무늬가 아니라 **세로 줄무늬**가 된다. 행으로 칠하려면 한 행에
 *    놓인 칸 **둘 다**를 집어야 하고, 그것을 아는 것은 이 계산뿐이다.
 *
 * ⚠️ **좁은 폭에서는 쓰지 말 것.** 1열로 접히면 행 번호가 곧 칸 순서(i)라
 *    이 함수가 필요 없고, 쓰면 오히려 틀린다. 쓰는 쪽은 `bg-…`(좁은 폭,
 *    i 기준)와 `lg:bg-…`(넓은 폭, 이 함수 기준) **둘 다** 건다.
 *
 * ⚠️ 「홀수 행」은 **`값 % 2 === 0`** 이다(0부터 세므로 0·2·4 가 1·3·5번째다).
 *    레퍼런스는 `nth-last-child(odd)` 로 **아래에서** 세는데, 거기는 7행이라
 *    위에서 세는 것과 결과가 같다. 우리는 **위에서** 센다 — 첫 행이 칠해져
 *    `border-t-2 border-ink` 바로 밑에서 표가 닫히는 쪽이 맞고, 회사 개요
 *    (7행)와 연락처(4행)의 **규칙이 같아진다**(연락처는 아래에서 세면 첫 행이
 *    흰색이 되어 두 쪽이 달라 보인다).
 *
 * ⚠️ 위 함수와 같은 경고가 그대로 적용된다 — **DOM 좌표로 재서 확인한다.**
 *    칸마다 `getBoundingClientRect().top` 을 읽어 **y 로 묶으면** 실제 행이
 *    나오고, 그것이 이 계산과 같아야 한다(돌린 기록은 두 쪽 주석에 있다).
 *
 * @param isWide i 번째 칸이 한 줄을 통째로 쓰는가
 * @returns 칸마다의 행 번호(0부터). 전폭 칸은 자기 혼자 한 행을 쓴다.
 */
export function gridRows(
  count: number,
  cols: number,
  isWide: (i: number) => boolean = () => false,
): number[] {
  const out: number[] = [];
  let row = 0;
  let col = 0;
  for (let i = 0; i < count; i++) {
    if (isWide(i)) {
      if (col > 0) row++; // 쓰던 줄이 반만 찼으면 닫는다
      out.push(row);
      row++; // 전폭 칸이 한 줄을 통째로 쓰므로 다음은 새 줄이다
      col = 0;
      continue;
    }
    out.push(row);
    col = (col + 1) % cols;
    if (col === 0) row++;
  }
  return out;
}
