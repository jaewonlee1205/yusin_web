/* 〈회사 개요〉 표 위에 서는 건물 그림. **사진이 아니라 코드로 그린다.**

   2026-10-20(13) — 사진을 네 판 갈아 끼운 끝에 여기로 왔다. 내력이 길어
   맨 앞에 결론부터 둔다 —

     판 (9)  유신이 준 항공 사진 → 정면 사진, 3:1 로 축소
     판 (10) 2176px 로 다시 구움 (뭉개짐은 압축이 아니라 확대 탓이었다)
     판 (11) 채도 0.25 필터로 지도와 채도를 맞춤
     ⚠️ 클래스 이름을 꼴 그대로 적지 않는다 — 이 파일은 **어디서도 안 쓰는데도**
        Tailwind 가 src/ 전체를 긁으므로 빌드 CSS 에 죽은 규칙이 남는다
        (판 (21) 에서 찾아 고쳤다)
     판 (12) 무료 흑백 사진으로 교체, 필터는 걷음
     판 (13) **코드로 그린 SVG** ← 지금

   유신의 말 — *"이거 이미지 보다 너가 코드로 회사 만드는게 디자인 적으로
   더 이쁠거 같기도 하고 지도 형태의 색감 형태로 회사 건물 외관 형태로
   디자인해서 … 현재 이미지도 디테일 하게 보면 **지도에 회색하고 현재
   이미지에 회색하고는 차이가 커서**"*

   ⚠️⚠️ **내가 잘못된 축을 맞추고 있었다.** 판 (12) 에서 나는 **채도**를
      재서 *"필터 없이 지도보다 더 회색입니다"* 라고 보고했다. 그런데
      유신이 본 차이는 거기 없었다. **밝기**를 재니 —

        지도        평균 밝기 226/255   192 이상이 94%
        그 사진     평균 밝기 159/255   중간~어두운 쪽에 퍼지고 검정도 5%

      **70 이나 벌어져 있었다.** 지도는 거의 흰 종이에 연회색 도형이고
      사진은 중간 회색 덩어리다. 같은 「회색」이라도 다른 세계다.
      한 축(채도)만 재고 통과시킨 것이 실수였다.

   ⚠️ **그리고 이 축은 사진으로 못 맞춘다.** 평균 밝기 226 짜리 건물
      사진은 사실상 없다 — 하늘도 희고 건물도 흰 사진이라야 하는데 그러면
      형태가 안 보인다. **코드로 그리면 색을 한 자리씩 정할 수 있다.**

   덤이 둘 — **화질 문제가 영구히 끝나고**(벡터라 어느 배율에서도 선명.
   판 (9)~(11) 을 통째로 먹은 그 문제다), **102KB 가 몇 KB 로** 준다. */

/* 색 사다리. **지도에서 뽑은 값이다.**

   `/location` 지도를 1086x362 로 찍어 색을 집계했다(saturate-50 을 먹은
   뒤의 값) —

     240,240,224  22%   바탕(약간 따뜻한 흰색)
     224,224,224  35%   건물 블록
     192,192,208  11%   도로
     240,240,240  10%   흰색

   ⚠️⚠️ **가장 어두운 값도 170 아래로 내리지 않는다.** 지도에 그보다
      어두운 면이 거의 없다. 이 한 줄이 이 그림의 전부다 — 창문을
      「보이게」 하려고 진하게 내리는 순간 판 (12) 의 사진과 같은 자리로
      돌아간다.
   ⚠️ **sky 와 face 는 기존 토큰과 같은 값이다** — `--color-surface
      #f6f7f9` 와 `--color-line #e5e7eb`. 나머지 중간 회색만 여기서
      정의한다. 한 곳에서만 쓰는 값을 `@theme` 에 올리면 디자인 체계가
      괜히 불어난다.
   ⚠️ 다크 모드 대응은 **넣지 않는다.** globals.css 머리말에 *"B2B
      제조업 사이트라 다크 모드는 만들지 않는다"* 고 못박혀 있다. */
const C = {
  sky: "#f6f7f9", // 246 — --color-surface 와 같다
  face: "#e5e7eb", // 229 — --color-line 과 같다. 건물 정면
  side: "#d6d9de", // 214 — 오른쪽 그늘면 · 입구
  win: "#c3c7ce", // 195 — 창
  line: "#b4b9c1", // 180 — 지붕선 · 지면선. **여기가 바닥이다**
  ground: "#dcdfe4", // 220 — 지면
} as const;

/* 건물 여섯. 가운데가 가장 높고 좌우로 낮아진다.

   ⚠️ **x 를 0 에서 1200 까지 빈틈없이 채운다.** 처음엔 양 끝에 하늘을
      남겼는데, 3:1 로 납작한 칸이라 좌우 여백이 **잘린 것처럼** 보였다.
   ⚠️ **합이 정확히 1200 이어야 한다** — 190+212+298+180+160+160.
      하나를 고치면 이웃도 고쳐야 한다.
   ⚠️ 유신이 있는 **지식산업센터의 성격**(반듯한 중층, 반복되는 창)만
      참고했다. 특정 건물을 그린 것이 아니라 `alt` 에 적을 것이 없다 —
      이 그림은 장식이고, 회사 정보는 바로 아래 표에 다 있다. */
const BUILDINGS = [
  { x: 0, y: 215, w: 190 },
  { x: 190, y: 174, w: 212 },
  { x: 402, y: 112, w: 298, entry: true },
  { x: 700, y: 154, w: 180 },
  { x: 880, y: 198, w: 160 },
  { x: 1040, y: 222, w: 160 },
] as const;

const GROUND_Y = 348;
const SIDE_W = 18; // 오른쪽 그늘면 폭
const WIN_W = 36;
const WIN_H = 26;
const COL = 48; // 창 가로 간격
const ROW = 42; // 창 세로 간격

/* 창을 코드로 깐다.

   ⚠️⚠️ **창 크기는 390px 폭이 정한다.** 거기서 칸이 348x116 이라
      viewBox 1200 이 **0.29배**로 줄어든다. 창 36 이 약 10px 이 되는데,
      이보다 작게 잡으면 휴대폰에서 격자가 **회색 얼룩**으로 뭉친다.
      넓은 화면에서 성겨 보여도 이 크기를 줄이지 말 것.
   ⚠️ `<pattern>` 을 쓰지 않고 사각형을 직접 깐다. 건물마다 폭이 달라
      좌우 여백이 들쭉날쭉해지는데, pattern 은 타일 원점이 고정이라
      그걸 못 맞춘다. 그리고 id 충돌도 피한다 — 한 화면에 이미
      `hero-dots` 와 `cta-dots` 가 있다. */
function windows({
  x,
  y,
  w,
  entry,
}: {
  x: number;
  y: number;
  w: number;
  entry?: boolean;
}) {
  const inner = w - SIDE_W;
  const cols = Math.max(1, Math.floor((inner - 24 + (COL - WIN_W)) / COL));
  const used = cols * COL - (COL - WIN_W);
  const pad = Math.max(12, Math.round((inner - used) / 2));
  const out: { x: number; y: number }[] = [];
  /* ⚠️ **입구가 선 건물은 맨 아랫줄을 비운다.** 처음엔 이 줄을 그대로
        두었더니 캐노피가 창 위에 **겹쳐** 얹혀 1층이 뭉개져 보였다.
        입구 높이(52)와 캐노피(8)와 틈(4)을 합한 만큼 한계를 올린다. */
  const bottom = GROUND_Y - (entry ? 64 : 16);
  for (let wy = y + 20; wy + WIN_H < bottom; wy += ROW) {
    for (let i = 0; i < cols; i++) out.push({ x: x + pad + i * COL, y: wy });
  }
  return out;
}

export default function CompanyBuilding() {
  return (
    /* ⚠️ viewBox 가 **정확히 3:1** 이라 바깥 `aspect-[3/1]` 칸과 맞아
          떨어진다. 그래서 잘리는 곳이 없다 — 비율을 바꾸려면 둘을 같이
          고쳐야 한다.
       ⚠️ `aria-hidden` — 장식이다. 화면 낭독기는 건너뛰고 바로 아래
          〈회사 개요〉 표를 읽는다. */
    <svg
      viewBox="0 0 1200 400"
      className="absolute inset-0 h-full w-full"
      aria-hidden="true"
      focusable="false"
    >
      <rect width="1200" height="400" fill={C.sky} />

      {BUILDINGS.map((b) => (
        <rect
          key={`f${b.x}`}
          x={b.x}
          y={b.y}
          width={b.w}
          height={GROUND_Y - b.y}
          fill={C.face}
        />
      ))}

      {/* 오른쪽 한 겹만 그늘로 둔다. 빛이 왼쪽에서 온다는 약속이고,
          이것만으로 건물이 납작한 종이에서 덩어리가 된다. */}
      {BUILDINGS.map((b) => (
        <rect
          key={`s${b.x}`}
          x={b.x + b.w - SIDE_W}
          y={b.y}
          width={SIDE_W}
          height={GROUND_Y - b.y}
          fill={C.side}
        />
      ))}

      {/* 지붕선. ⚠️ **이 선이 있고 없고가 컸다.** 없이도 그려 봤는데
          면끼리 명도 차가 작아 건물 경계가 뭉개졌다. 5px 선 하나로
          여섯 덩어리가 갈린다. */}
      {BUILDINGS.map((b) => (
        <rect
          key={`p${b.x}`}
          x={b.x}
          y={b.y}
          width={b.w}
          height={5}
          fill={C.line}
        />
      ))}

      {BUILDINGS.flatMap((b) =>
        windows(b).map((w) => (
          <rect
            key={`w${w.x}-${w.y}`}
            x={w.x}
            y={w.y}
            width={WIN_W}
            height={WIN_H}
            fill={C.win}
          />
        )),
      )}

      {/* 가장 높은 건물 1층의 입구와 캐노피. 건물 무리에 **중심**을 준다. */}
      <rect x={491} y={GROUND_Y - 52} width={120} height={52} fill={C.side} />
      <rect x={469} y={GROUND_Y - 60} width={164} height={8} fill={C.line} />

      {/* 지면. ⚠️ 맨 아래 8px 이 표의 `border-y-2 border-ink` 와 맞닿는다.
             220 이라 먹색 선이 또렷하게 갈린다(사진 시절 이 값 때문에
             두 판을 썼다). 어둡게 내리지 말 것. */}
      <rect x={0} y={GROUND_Y} width={1200} height={400 - GROUND_Y} fill={C.ground} />
      <rect x={0} y={GROUND_Y} width={1200} height={3} fill={C.line} />
    </svg>
  );
}
