"use client";

import { useEffect, useState } from "react";

/**
 * 지도 위에 깔리는 **보이지 않는 차단막**. 색은 없다 — 네이비 색조는 옆의
 * 다른 겹이 맡는다(location/page.tsx 참고). 이것은 **손짓만** 다룬다.
 *
 * ⚠️⚠️⚠️ **구글 지도 iframe 의 안내 막을 안 뜨게 하려고 있다.**
 *    *"지도를 확대/축소하려면 Ctrl을 누른 채 스크롤하세요."* ·
 *    *"지도를 이동하려면 두 손가락으로 움직이세요."* — 유신이 둘 다
 *    *"삭제 하고 싶다"* 고 했다. 그 문구는 **우리 글이 아니라** 구글이 제
 *    iframe 안에서 띄우는 것이고, **교차 출처라 CSS 로도 JS 로도 못
 *    숨긴다.** 없애는 길은 **손짓이 iframe 에 닿지 않게 하는 것** 하나뿐이다.
 *
 * ⚠️⚠️⚠️ **2026-10-21 판 (23) — 「전부 막기」에서 「가려서 막기」로 바꿨다.**
 *    판 (22) 에서는 겹 하나가 지도를 **통째로** 막았다. 그랬더니 유신이
 *    *"오른쪽 옆에 **전체 크게보기 확장 버튼**이나 왼쪽옆에 **이미지 보기**
 *    같은거 … 이거 **눌러도 동작하지 않고** ctrl 버튼 누른 상태에서 움직여도
 *    **지도 아무것도 동작을 안하는데?**"* 라고 했다.
 *    **내가 대가를 잘못 골랐다.** 없애야 했던 것은 안내 막이지 지도가
 *    아니었다. 유신이 *"ctrl 버튼 누른 상태에서"* 라고 쓴 것은 **구글의
 *    규칙을 이미 알고 그대로 하고 있었다**는 뜻인데, 그 길을 내가 막았다.
 *
 *    구글의 규칙은 **「ctrl+휠이면 확대, 그냥 휠이면 안내 막」**이다.
 *    그래서 **손짓을 가려서 통과시킨다** —
 *
 *      그냥 휠·터치   막는다      페이지가 내려간다. 안내 막이 안 뜬다
 *      ctrl(⌘) 누름   비켜선다    지도가 확대·이동된다.
 *                                 **안내 막도 안 뜬다** — ctrl 을 눌렀으니
 *                                 구글이 띄울 까닭이 없다
 *      구석도 안 비운다  판 (26) 부터 **온 칸**을 막는다. 좌하단 지도/위성
 *                        버튼은 판 (27) 에서 **지도를 왼쪽으로 밀어 칸 밖으로**
 *                        내보냈고(location/page.tsx), 우하단 전체화면 버튼은
 *                        **보이지만 이 막에 걸려 안 눌린다.** 유신이 둘 다
 *                        *"지우자"* 고 했으니 눌리게 할 까닭이 없다.
 *                        판 (23)~(25) 에는 왼쪽 아래 64x64 를 비워 두었다 —
 *                        거기 지도/위성 전환 버튼이 있었고 유신이 그건
 *                        남기라고 했기 때문이다. 판 (26) 에서 *"3개 다
 *                        지우자"* 로 바뀌었다
 *
 *    ⚠️ **모바일은 계속 막힌다.** 터치에는 ctrl 이 없다. 그래서 *"두
 *       손가락"* 문구도 계속 안 뜬다. ⚠️ 판 (26) 부터는 **지도 위에 누를
 *       것이 하나도 없다** — 크게 보려면 **아래 표의 주소**를 누른다.
 *       네이버 지도가 새 창으로 열리고, 휴대폰에서는 지도 앱으로 넘어간다.
 *       (판 (24) 에는 그 자리가 「길찾기」, 판 (25) 에는 「크게 보기」였다.)
 *
 *    ⚠️⚠️ **재서 확인했다 — 차단막을 걷은 대조군을 옆에 두고.** 지도 칸의
 *       어두운 픽셀 비율(구글의 막은 검은 반투명이라 치솟는다)로 쟀다:
 *
 *                         그냥 휠            ctrl+휠
 *         대조군(막 없음)  1.50% → 96.85%    0.56% · 지도 36.3% 바뀜
 *         지금 (판 23)     1.45% →  1.45%    0.57% · 지도 36.4% 바뀜
 *
 *       **ctrl+휠에서 바뀐 픽셀이 대조군과 같다**(36.4 vs 36.3) — 막이
 *       비켜서서 확대가 **그대로** 일어난다는 뜻이다. 그냥 휠에서는
 *       페이지가 0 → 300 으로 내려갔다. ctrl 을 뗀 뒤 다시 굴려도 안 떴다.
 */
export default function MapGuard() {
  /** ctrl(⌘) 이 눌려 있는 동안만 true — 그동안 이 막이 비켜선다. */
  const [pass, setPass] = useState(false);

  useEffect(() => {
    /* ⚠️ `e.key === "Control"` 만 보면 안 된다 — ctrl 을 누른 채 다른 키를
          눌렀을 때 그 keydown 의 key 는 "Control" 이 아니다. 수식어 상태를
          직접 읽는다. 맥의 ⌘ 도 같이 본다(구글은 맥에서 ⌘+스크롤을 쓴다). */
    const read = (e: KeyboardEvent) => setPass(e.ctrlKey || e.metaKey);

    /* ⚠️⚠️ **되돌리는 길이 반드시 있어야 한다.** ctrl 을 누른 채 Alt+Tab 으로
          창을 옮기면 **keyup 이 영영 안 온다** — 그대로 두면 막이 비켜선 채
          굳어 안내 문구가 되살아난다. 창을 떠나는 두 경로를 다 막는다.
          ⚠️ 재서 확인했다 — ctrl 을 누른 채 blur 를 보내면 pointer-events 가
             none → auto 로 되돌아온다. */
    const reset = () => setPass(false);

    window.addEventListener("keydown", read);
    window.addEventListener("keyup", read);
    window.addEventListener("blur", reset);
    document.addEventListener("visibilitychange", reset);
    return () => {
      window.removeEventListener("keydown", read);
      window.removeEventListener("keyup", read);
      window.removeEventListener("blur", reset);
      document.removeEventListener("visibilitychange", reset);
    };
  }, []);

  /* ⚠️ 판 (25) 까지는 막이 조각 둘이라 "둘 다 같이 비켜선다" 고 적혀
        있었다. 판 (26) 부터 한 겹이다. */
  const off = pass ? "pointer-events-none" : "";

  return (
    <>
      {/* ⚠️⚠️⚠️ **2026-10-21 판 (26) — 막이 ㄱ 자에서 다시 **온 칸**이 됐다.**
             유신이 지도 위의 버튼을 **셋 다 지우라고** 했고, 구글이 그리는
             둘(좌하단 지도/위성 · 우하단 전체화면)은 지울 수 없어
             **location/page.tsx 가 조각으로 덮었다.** 가려서 못 누르게 된
             이상 **구석을 비워 둘 까닭이 사라졌다.**

             ⚠️⚠️ **판 (22) 의 「전부 막기」와는 다르다.** 그때는 ctrl 을
                눌러도 지도가 꿈쩍 않아 유신이 *"ctrl 버튼 누른 상태에서
                움직여도 지도 아무것도 동작을 안하는데?"* 라고 했다. 지금은
                **ctrl 을 누르면 이 막이 통째로 비켜선다** — 확대도 이동도
                그대로 된다. 막는 것은 **그냥 휠과 맨 손가락**뿐이다.

             ⚠️ **덤 — 안내 막이 뜰 수 있는 자리가 0 이 됐다.** 판 (23)~(25)
                에서는 왼쪽 아래 64x64(지도 면적의 약 1%)가 비어 있어서
                **거기서 휠을 굴리면 안내 막이 떴다.** 막을 수 없는 자리였고,
                덮으면 지도/위성 버튼이 안 눌려서 둘 중 하나였다. 그 버튼이
                아예 가려진 지금은 **고를 것이 없다.**

             ⚠️ 지도 위에 눌릴 것이 하나도 없다 — 「길찾기」는 **표의 주소
                값**으로 옮겼고, iframe 은 Tab 에서 뺐다(tabIndex -1).
             ⚠️ aria-hidden 이다. 보조기기에는 없는 요소이고, 지도의 내용은
                아래 연락처 표가 글자로 전한다.
             ⚠️ 판 (26) 한 판 동안은 구글 UI 를 **지도색 조각**으로 덮었고,
                그 조각은 pointer-events-none 이라 이 막의 일을 가로채지
                않았다. **판 (27) 에서 유신이 그 조각을 물렸다**(*"회색 네모가
                이상하다"*). 지금 지도 위에 깔린 것은 **이 막과 색조 겹뿐**이다.
             ⚠️⚠️ **우하단 전체화면 버튼이 「보이는데 안 눌리는」 상태다.**
                판 (23) 에 유신이 *"눌러도 동작하지 않고 … ctrl 버튼 누른
                상태에서 움직여도 지도 아무것도 동작을 안하는데?"* 라고 했던
                것과 **헷갈리지 말 것** — 그때 문제는 **ctrl 로도 아무것도 안
                됐다**는 데 있었다. 지금은 ctrl 이면 이 막이 통째로 비켜서서
                확대도 이동도 된다. 그 버튼 하나만 일부러 죽여 둔 것이다. */}
      <div aria-hidden="true" className={`absolute inset-0 ${off}`} />
    </>
  );
}
