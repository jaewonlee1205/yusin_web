export type Video = {
  /**
   * 유튜브 영상이면 **유튜브 id**, 아니면 리액트 키 겸 파일 이름이다.
   * `src` 가 있는 항목은 유튜브에 없는 영상이라 이 값이 유튜브 id 가 아니다.
   */
  id: string;
  title: string;
  note: string;
  /**
   * /videos 의 「기종」 거르개 축. 갤러리(/clients)의 `workKinds` 와 같은
   * 일곱 글자를 쓴다 — 두 쪽 패널이 같아 보여야 한다.
   *
   * ⚠️⚠️ **지어 붙이지 않는다.** 위 TODO 가 적어 둔 대로 title 과 note 는
   *    썸네일을 보고 붙인 추정이라, 그 글에서 기종을 역추론하면 추정 위에
   *    추정을 쌓는 꼴이 된다.
   *
   *    아래 다섯 편을 「볼피더」로 두는 근거는 **유튜브 쪽 제목**이다 —
   *    "자동공급기(볼피더) 제조 전문기업, 유신F.A시스템 01~04". 유신이 직접
   *    볼피더라고 적은 것이고, 위 머리 주석이 그 제목을 이미 인용하고 있다.
   *
   *    제품 구동 영상 일곱(videoLibrary.ts)은 그 제품의 구동 영상이라
   *    기종이 정의상 정해진다.
   */
  kinds: string[];
  /**
   * 유튜브에 없는 **로컬 mp4**(public/videos/). 있으면 /videos 격자에서
   * 누를 때 유튜브 iframe 대신 이 파일이 그 자리에서 돈다(VideoEmbed).
   *
   * ⚠️ `preview` 와 다르다. preview 는 **홈에서 저절로 도는 장식 영상**이고
   *    이것은 /videos 에서 **눌러야 도는 본 영상**이다. 한 편이 둘 다 가질
   *    수 있다(홈 전용 영상이 그렇다).
   */
  src?: string;
  /**
   * 소리 없이 저절로 도는 미리보기 파일(public/videos/).
   *
   * 있는 영상만 홈에 올라간다(아래 featuredVideos). 유튜브 임베드로도 자동
   * 재생을 걸어 봤지만 플레이어 자체의 결 — 로딩 화면, 루프 이음매, 화질
   * 전환 — 이 남아 "유튜브 미리보기" 로 보였다. 히어로.PERFORMANCE 가 쓰는
   * 로컬 <video> 와 같은 꼴로 맞춘다.
   *
   * 홈에서는 **누를 것이 없는 장식 영상**이다 — 재생 버튼도, 호버 반응도
   * 없다. 유튜브로 가는 길은 섹션의 "영상 전체 보기" 버튼과 /videos 가
   * 맡는다(VideoEmbed 머리 주석 참고).
   *
   * 만드는 법은 README "제품 영상 미리보기 만들기" 참고. 원본 촬영본은
   * 저장소에 없다(yusin-web 바로 위 폴더).
   */
  preview?: string;
  /**
   * 홈 미리보기의 첫 화면(public/images/videos/). **그 미리보기 mp4 의 첫
   * 프레임**이어야 한다.
   *
   * 없으면 VideoEmbed 가 유튜브 썸네일로 떨어지는데, 그건 **다른 그림**이다 —
   * 같은 촬영본이라도 다른 순간이라 영상이 뜨는 순간 그림이 **한 번 바뀐다**.
   * 디졸브가 있던 동안은 그 바뀜이 페이드에 묻혔지만, 디졸브를 걷어 낸 뒤
   * (2b0c906) 는 그대로 번쩍임으로 보인다.
   *
   * 굽는 법 — ffmpeg -i <미리보기> -vf "select=eq(n,0)" -frames:v 1
   *           -c:v libwebp -compression_level 6 -quality 85 <포스터>
   * 네 장 다 첫 프레임과 SSIM 0.990~0.991 로 맞춰 두었다.
   *
   * ⚠️ /videos 파사드는 이걸 쓰지 않는다 — 거기선 유튜브 썸네일이 맞다
   *    (누르면 유튜브가 뜨니, 유튜브가 보여 줄 그림이어야 한다).
   */
  poster?: string;
};

