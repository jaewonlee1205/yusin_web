/**
 * related 의 slug 를 빌드 때 한 번 검사한다.
 *
 * related 가 string[] 이라 타입은 오타를 못 잡고, 상세 페이지의 find 는 못
 * 찾은 slug 를 조용히 건너뛴다 — 카드 한 장이 말없이 사라지는 게 가장 나쁘다.
 * 여기서 던지면 빌드가 멈춘다.
 */
for (const p of products) {
  // 한 제품의 applications 가 문자열과 객체로 섞이면 같은 목록에 칩과 사진
  // 카드가 함께 나온다. 화면에서는 어긋난 격자로만 보여 알아채기 어렵다.
  const withPhoto = p.applications.filter((a) => typeof a !== "string").length;
  if (withPhoto !== 0 && withPhoto !== p.applications.length) {
    throw new Error(
      `products.ts: ${p.slug} 의 applications 에 칩과 사진 카드가 섞여 있다`
    );
  }

  // 구동 영상은 public/videos/ 의 로컬 파일이다. 유튜브 영상(videos.ts)과
  // 섞이면 자동 재생이 안 되는 것이 화면에서만 드러난다.
  if (!p.video.src.startsWith("/videos/") || !p.video.src.endsWith(".mp4")) {
    throw new Error(
      `products.ts: ${p.slug} 의 video.src 가 /videos/*.mp4 가 아니다`
    );
  }
  if (!p.video.poster.endsWith(".webp")) {
    throw new Error(`products.ts: ${p.slug} 의 video.poster 가 .webp 가 아니다`);
  }

  // KPI 띠는 네 칸 격자다. 셋이면 마지막 칸이 비고, 다섯이면 둘째 줄에
  // 한 칸만 선다. 어느 쪽이든 화면에서는 "덜 채운 격자" 로만 보인다.
  if (p.kpis.length !== 4) {
    throw new Error(
      `products.ts: ${p.slug} 의 kpis 는 넷이어야 한다 (지금 ${p.kpis.length}개)`
    );
  }

  // 숫자 뒤의 레드 단위가 이 띠의 리듬이다. 한 칸만 비어도 거기서 끊긴다.
  for (const k of p.kpis) {
    if (!k.unit) {
      throw new Error(`products.ts: ${p.slug} 의 kpis "${k.label}" 에 unit 이 없다`);
    }
  }

  for (const slug of p.related) {
    if (slug === p.slug) {
      throw new Error(`products.ts: ${p.slug} 의 related 가 자기 자신을 가리킨다`);
    }
    if (!products.some((q) => q.slug === slug)) {
      throw new Error(`products.ts: ${p.slug} 의 related 에 없는 slug "${slug}"`);
    }
  }
}

export function getProduct(slug: string): Product | undefined {
  return products.find((p) => p.slug === slug);
}
