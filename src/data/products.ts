export type ProductCategory = (typeof CATEGORIES)[number];

export type Product = {
  slug: string;
  name: string;
  nameEn: string;
  category: ProductCategory;
  /**
   * 설명이 세 겹이다. 쓰이는 자리가 다르고 길이 제약도 달라 나눠 둔다.
   * 짧은 것부터 tagline -> summary -> lead 순이다.
   */

  /**
   * 카드 설명(ProductCard). 제품이 어떻게 동작하는지를 말한다.
   *
   * ⚠️ 어느 폭에서나 두 줄이어야 한다. 30~37자가 그 구간이다.
   *    28자 밑으로 내려가면 가장 넓은 칸(297px, 홈 격자 1280 이상)에서
   *    한 줄로 떨어지고, 38자를 넘기면 가장 좁은 칸(217px, 제품 페이지
   *    1280 이상 3열)에서 세 줄이 된다. 일곱 개를 폭 10종
   *    (217.219.223.249.263.283.290.291.294.297)에서 재서 전부 2줄이다.
   *
   * 한 장만 줄 수가 달라지면 그 카드의 글 뭉치만 떠 보인다.
   * 전문 용어(판스프링.전자석.흡음재.센서)를 그대로 쓴다.
   */
  tagline: string;
  /**
   * 제품 상세 히어로의 한 줄 요약(products/[slug]/page.tsx).
   * 제품이 무엇이고 어디에 쓰는지를 규정한다. 제품명 바로 밑에 18px 로
   * 놓이고, 그다음 줄이 lead 문단이다.
   *
   * ⚠️ 한 줄에 가깝게 — 28~36자. 1440에서 히어로 오른쪽 칸이 약 544px 라
   *    36자면 한 줄이고, 더 길어지면 두 줄로 흘러 아래 lead 와 덩어리가
   *    된다(요약이 요약으로 안 보인다).
   *
   * 바로 아래 lead 문단과 같은 구절을 쓰지 말 것. 둘이 붙어 나온다.
   *
   * 전에는 이 값이 네이비 배너의 lead 였다. 상세에서 배너를 걷어내면서
   * 자리가 바뀌었다 — 그때는 "640px 에서 한 줄 / 320px 에서 두 줄" 이
   * 배너 높이(240/232px)를 지키는 조건이었다.
   */
  summary: string;
  /**
   * 검색 결과 설명 전용(generateMetadata 의 description · og:description).
   *
   * ⚠️ 화면에는 나오지 않는다. 전에는 히어로의 설명 문단이었는데, 그 문단이
   *    사실 features.title 을 산문으로 늘여 쓴 것이어서 히어로에서는
   *    "주요 특징" 체크 목록으로 바뀌었다(page.tsx 주석 참고). 그래도 이
   *    필드는 지운다 — 검색 결과 설명은 목록이 아니라 산문이어야 한다.
   *
   * ⚠️ 90~105자. 이제는 레이아웃 제약이 아니라 검색 설명 길이다. 구글이
   *    데스크톱에서 대략 920px(한글 60자 안팎)까지 보여 주고 뒤를 자르므로
   *    앞쪽에 제품이 무엇인지가 와야 한다. 105자를 넘기면 뒤가 통째로
   *    버려진다.
   */
  lead: string;
  /**
   * 특징. 개수는 **짝수**로 둔다 — 지금 2개 또는 4개다.
   *
   * ⚠️ 2열 격자라 홀수면 마지막 행에 칸이 하나 빈다. 한때 2~4개를 자유롭게
   *    뒀는데 네 제품이 3개가 되어 그 빈 칸이 네 페이지에 나타났다.
   *
   * ⚠️ 아래 specs 에 같은 내용이 행으로 있으면 여기 적지 말 것.
   *    한때 일곱 제품을 전부 4개로 채웠는데, 채운 여섯 개가 모두 사양 표에
   *    이미 있는 말이어서 한 페이지에서 같은 내용을 두 번 읽게 됐다.
   *    개수를 맞추려고 적는 특징은 특징이 아니다.
   *
   * ⚠️ 길이 규칙. 둘 다 어느 폭에서나 한 줄이어야 한다.
   *
   *    title  한 줄이어야 한다. 특징이 두 열이라 항목 칸이 1280 이상에서
   *           556px, 1024 에서 453px 이고, 거기서 번호(22px)와 간격(12px)을
   *           뺀 제목 칸이 522px / 419px 다. 지금 가장 긴 제목이 163px
   *           ("선별 · 방향 판별 지그")라 320px 글상자에서도 한 줄이다.
   *
   *    body   680~800px(60~71자). **640 이상에서 스무 개가 모두 두 줄**이
   *           되는 구간이다. 한 줄과 두 줄이 섞이면 항목 높이가 들쭉날쭉해
   *           보이므로 전부 두 줄로 맞췄다.
   *
   *           구간을 어떻게 구했는지: 본문 칸이 폭마다 231(320) · 301(390) ·
   *           527(640) · 655(768) · 418(1024) · 490(1280 이상)px 다. 1024 가
   *           가장 좁다 — 2열인데 Container 가 945px 뿐이라 768(1열, 655px)
   *           보다도 좁다. "글자 폭 > 칸" 이면 두 줄이므로 640~1440 의
   *           교집합이 656~836px 이고, 양쪽에 24~36px 여유를 둔 값이 위
   *           범위다.
   *
   *           ⚠️ 320·390 은 칸이 231/301px 라 어떤 글이든 세 줄 이상이 된다.
   *              거기까지 균일하게 맞추려면 구간이 656~693px(3자 폭)로 좁아져
   *              스무 개를 넣을 수 없다. 640 이상을 기준으로 삼는다.
   */
  features: { title: string; body: string }[];
  /**
   * 제작 시 선택하는 항목. 여섯 줄로 맞춘다.
   *
   * ⚠️ 순서가 중요하다. **앞 세 줄**은 상세 히어로의 "주요 사양" 카드가
   *    가져가고, **뒤 세 줄**만 아래 사양 표에 남는다(slice(0,3) / slice(3)).
   *    같은 줄이 한 페이지에 두 번 나오지 않게 나눈 것이므로, 고객이 먼저
   *    알아야 하는 것을 앞에 둘 것.
   *
   * ⚠️ 길이. 앞 세 줄의 value 는 히어로에서 13px 로 그려지고 값 칸이 가장
   *    좁아지는 곳이 1024(308px) 다 — 지금 가장 긴 것이 246px 다. 뒤 세 줄은
   *    표에서 14px 이고 dd 칸이 768에서 542px 라 훨씬 여유가 있다(최대 282px).
   *
   * label 은 14px bold 로 9rem(144px) 칸에 들어가야 한다 — 글상자 104px,
   * 지금 가장 긴 것이 68px("거칠기 등급")다.
   */
  specs: { label: string; value: string }[];
  /**
   * 적용 분야 칩. 개수를 제품마다 맞추지 않는다 — 지금 2~5개다.
   *
   * ⚠️ 서로 다른 자리·다른 부품을 가리킬 때만 따로 적을 것. "장시간 무인
   *    운전 라인" 과 "야간·주말 연속 가동 설비" 처럼 같은 말을 둘로 쪼개
   *    숫자를 채우지 않는다.
   */
  applications: string[];
  /**
   * 상세 페이지 아래 "다른 제품" 에 띄울 제품의 slug.
   *
   * ⚠️ 개수를 맞추지 않는다 — 실제로 함께 쓰는 것만 적는다(지금 2~3개).
   *    전에는 목록을 돌려 가며 셋씩 뽑았는데(`[1,2,3].map`), 그러면 칸을
   *    채우려고 관련 없는 제품도 끌어왔다.
   *
   * 근거는 그 제품 specs 에 적힌 연결 관계다. 파일 끝의 검사가 없는 slug 와
   * 자기 자신을 빌드 때 잡는다.
   */
  related: string[];
  images: { src: string; alt: string }[];
};

